package com.example.demo.config;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * OpenAPI 3 / Swagger configuration.
 * Generates interactive interactive documentation accessible at /swagger-ui/index.html.
 * Configures global JWT Bearer authentication scheme for protected endpoints.
 */
@Configuration
public class OpenApiConfig {

    private static final String SECURITY_SCHEME_NAME = "bearerAuth";

    @Bean
    public OpenAPI careerLinkOpenAPI() {
        return new OpenAPI()
                .info(new Info()
                        .title("CareerLink Enterprise REST API")
                        .description("Comprehensive REST API specification with stateless JWT authentication for the CareerLink Job Portal.")
                        .version("v1.0.0")
                        .contact(new Contact()
                                .name("CareerLink Engineering Team")
                                .email("engineering@careerlink.local"))
                        .license(new License()
                                .name("Apache 2.0")
                                .url("https://springdoc.org")))
                .addSecurityItem(new SecurityRequirement().addList(SECURITY_SCHEME_NAME))
                .components(new Components()
                        .addSecuritySchemes(SECURITY_SCHEME_NAME, new SecurityScheme()
                                .name(SECURITY_SCHEME_NAME)
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")
                                .description("Enter your JWT access token generated by /api/v1/auth/login to authorize requests.")));
    }
}
